-- Ejecutar una vez en el SQL Editor de Supabase.
-- Crea la tabla de eventos y el bucket público donde se suben las capturas.

create table if not exists public.eventos (
  id bigint generated by default as identity primary key,
  momento text not null,
  zona text not null,
  falta_casco integer not null default 0,
  falta_chaleco integer not null default 0,
  confianza real,
  ruta_captura text,
  latitud double precision,
  longitud double precision,
  precision_m double precision,
  origen text default 'video',
  usuario text
);

create index if not exists idx_eventos_zona_momento on public.eventos (zona, momento);

-- El servidor usa la clave service_role, que bypassa RLS. Estas políticas
-- permiten además leer desde el panel con la clave anon, si se decide usarla.
alter table public.eventos enable row level security;
drop policy if exists "lectura_publica_eventos" on public.eventos;
create policy "lectura_publica_eventos" on public.eventos for select using (true);
drop policy if exists "insercion_publica_eventos" on public.eventos;
create policy "insercion_publica_eventos" on public.eventos for insert with check (true);

insert into storage.buckets (id, name, public)
values ('capturas', 'capturas', true)
on conflict (id) do nothing;

drop policy if exists "lectura_publica_capturas" on storage.objects;
create policy "lectura_publica_capturas" on storage.objects
  for select using (bucket_id = 'capturas');
drop policy if exists "insercion_publica_capturas" on storage.objects;
create policy "insercion_publica_capturas" on storage.objects
  for insert with check (bucket_id = 'capturas');
